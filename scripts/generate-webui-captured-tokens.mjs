import { readFileSync, writeFileSync } from 'node:fs';

/**
 * Wire design capture/verify to the WebUI token source (Kanban card d91f721f,
 * .design/review.md Follow-up 12 finding 13).
 *
 * The design tool snapshots repo-root src/styles/design-tokens.css (the
 * website) and its capture action takes no path override. It DOES read
 * .design/captured-tokens.json — so this script generates that file from
 * packages/webui/src/index.css, mapping the WebUI's HSL-triple tokens into
 * the tool's semantic slots (light from `:root`, dark from `.dark`).
 * Rerun after any index.css token change, then run design verify.
 *
 * Run with: node scripts/generate-webui-captured-tokens.mjs
 */

const CSS = 'packages/webui/src/index.css';
const OUT = '.design/captured-tokens.json';

const css = readFileSync(CSS, 'utf8');
const lines = css.split(/\r?\n/);

// The first `:root {` inside `@layer base` is light; the following `.dark {` is dark.
const lightStart = lines.findIndex((l) => l.trim() === ':root {');
const darkStart = lines.indexOf('  .dark {', lightStart);

function block(start, end) {
  const map = {};
  for (let i = start; i < end; i += 1) {
    const m = lines[i].match(/^\s*--([a-z-]+):\s*([^;]+);/);
    if (m) map[m[1]] = m[2].trim();
  }
  return map;
}
const light = block(lightStart, darkStart);
const dark = block(
  darkStart,
  lines.findIndex((l, index) => index > darkStart && l.trim() === '}'),
);

const hsl = (v) => (v ? `hsl(${v})` : undefined);
const SLOTS = {
  bg: '--background',
  surface: '--card',
  raised: '--secondary',
  fg: '--foreground',
  muted: '--muted-foreground',
  primary: '--primary',
  accent: '--accent',
  success: '--success',
  warning: '--warning',
  danger: '--destructive',
  border: '--border',
  ring: '--ring',
};
const pick = (blockTokens) =>
  Object.fromEntries(
    Object.entries(SLOTS).map(([slot, token]) => [
      slot,
      hsl(blockTokens[token.replace(/^--/, '')]),
    ]),
  );

const out = {
  stack: 'web',
  capturedAt: new Date().toISOString(),
  files: [CSS],
  source:
    'generated by scripts/generate-webui-captured-tokens.mjs — do not hand-edit; rerun the script after index.css token changes',
  tokens: { light: pick(light), dark: pick(dark) },
  palettes: {},
};
for (const [mode, tokens] of Object.entries(out.tokens)) {
  const missing = Object.entries(tokens)
    .filter(([, v]) => !v)
    .map(([k]) => k);
  if (missing.length) throw new Error(`${mode} tokens missing: ${missing.join(', ')}`);
}
writeFileSync(OUT, `${JSON.stringify(out, null, 1)}\n`);
console.log(`captured ${Object.keys(SLOTS).length} semantic slots x2 modes -> ${OUT}`);
